const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('evPet', {
  onPointer: (callback) => ipcRenderer.on('pointer', (_event, value) => callback(value)),
  onPointerDown: (callback) => ipcRenderer.on('global-pointer-down', (_event, value) => callback(value)),
  onPointerUp: (callback) => ipcRenderer.on('global-pointer-up', (_event, value) => callback(value)),
  onDrag: (callback) => ipcRenderer.on('global-drag', (_event, value) => callback(value)),
  onActivity: (callback) => ipcRenderer.on('activity', (_event, value) => callback(value)),
  onCommand: (callback) => ipcRenderer.on('command', (_event, value) => callback(value)),
  onWindowChange: (callback) => ipcRenderer.on('window-change', (_event, value) => callback(value)),
  onChatFocus: (callback) => ipcRenderer.on('chat-focus', callback),
  onConfig: (callback) => ipcRenderer.on('config', (_event, value) => callback(value)),
  onRuntimeState: (callback) => ipcRenderer.on('runtime-state', (_event, value) => callback(value)),
  onDialogueReply: (callback) => ipcRenderer.on('dialogue-reply', (_event, value) => callback(value)),
  onSettingsChange: (callback) => ipcRenderer.on('settings-change', (_event, value) => callback(value)),
  onStatus: (callback) => ipcRenderer.on('status-change', (_event, value) => callback(value)),
  saveConfig: (value) => ipcRenderer.invoke('save-config', value),
  applySettings: (value) => ipcRenderer.send('settings-change', value),
  reportStatus: (value) => ipcRenderer.send('status-change', value),
  quitApp: () => ipcRenderer.invoke('quit-app'),
  submitCommand: (value) => ipcRenderer.send('submit-command', value),
  closeChat: () => ipcRenderer.send('close-chat'),
  openChat: () => ipcRenderer.send('open-chat'),
  reportDialogue: (value) => ipcRenderer.send('dialogue-reply', value),
  getCompanionMs: () => ipcRenderer.invoke('get-companion-ms'),
  reportCollection: (value) => ipcRenderer.send('collection-change', value),
  onCollectionUpdate: (callback) => ipcRenderer.on('collection-update', (_event, value) => callback(value)),
  reportPomodoro: (value) => ipcRenderer.send('pomodoro-state', value),
  onPomodoroState: (callback) => ipcRenderer.on('pomodoro-state', (_event, value) => callback(value)),
  getPathForFile: (file) => webUtils.getPathForFile(file),
  reportFileDrop: (paths) => ipcRenderer.send('file-drop', paths),
  onFeedOffer: (callback) => ipcRenderer.on('feed-offer', (_event, value) => callback(value)),
  onFeedConfirmed: (callback) => ipcRenderer.on('feed-confirmed', (_event, value) => callback(value)),
  confirmFeed: () => ipcRenderer.send('feed-confirm'),
  cancelFeed: () => ipcRenderer.send('feed-cancel'),
  openBrowser: () => ipcRenderer.send('open-browser'),
  openFunction: (page) => ipcRenderer.send('open-function', page),
  onOpenFunction: (callback) => ipcRenderer.on('open-function', (_event, value) => callback(value)),
  loadState: () => ipcRenderer.invoke('load-state'),
  saveState: (patch) => ipcRenderer.send('save-state', patch),
  remind: (text) => ipcRenderer.send('remind', text),
  onRemind: (callback) => ipcRenderer.on('remind', (_event, value) => callback(value)),
  reportBirthday: () => ipcRenderer.send('birthday'),
  onBirthday: (callback) => ipcRenderer.on('birthday', (_event) => callback()),
  reportPetPosition: (pos) => ipcRenderer.send('pet-position', pos),
  aiChat: (text) => ipcRenderer.invoke('ai-chat', text)
});
